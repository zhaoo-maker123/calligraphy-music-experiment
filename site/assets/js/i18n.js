let activeLanguage = readStoredLanguage();

function readStoredLanguage() {
  try {
    const stored = globalThis.localStorage?.getItem(LANGUAGE_STORAGE_KEY);
    return stored === "en" ? "en" : "zh";
  } catch {
    return "zh";
  }
}

export function getLanguage() {
  return activeLanguage;
}

export function setLanguage(language) {
  activeLanguage = language === "en" ? "en" : "zh";
  try {
    globalThis.localStorage?.setItem(LANGUAGE_STORAGE_KEY, activeLanguage);
  } catch {
    // The interface still switches when browser storage is unavailable.
  }
  if (globalThis.document?.documentElement) {
    globalThis.document.documentElement.lang = activeLanguage === "en" ? "en" : "zh-CN";
  }
  return activeLanguage;
}

export function t(key, variables = {}) {
  const template = MESSAGES[activeLanguage][key] ?? MESSAGES.zh[key] ?? key;
  return Object.entries(variables).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function translateState(state) {
  return t(`state.${state}`);
}
